/** Translate display names only; raw field identifiers and workspace data remain intact. */
export function bbText(value: string): string {
    if (i18n.getCurrentLocale() !== "zh_CN" || !value) return value;
    if (names[value]) return names[value];
    const workspace = value.match(/^(\d+\s+)(.*)$/);
    if (workspace && names[workspace[2]]) return workspace[1] + names[workspace[2]];
    return value.replace(/\b[A-Za-z]+\b/g, (word) => words[word] || word);
}
